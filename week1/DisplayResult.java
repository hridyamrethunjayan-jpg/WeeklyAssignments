//Creating class named DisplayResult

public class DisplayResult{
	public static void main(String args[]){
		//Creating String variable to store Sam as name
		String name="Sam";
		
		//Creating integer variable to store 1 as roll number
		int rollNumber=1;
		
		//Creating double variable to store 99.99 as percentage of marks
		double percentMarks=99.99;
		
		//Creating character variable to store P as result
		char result='P';
		
		//Displaying the result on the screen
		System.out.println(name+" with roll number "+rollNumber+" has scored "+percentMarks+" % marks and the result is "+result);
	}
}		